import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('progetto locale: video, TC, note persistenti, QC ed esportazione', async ({ page, request }, testInfo) => {
  const directory = mkdtempSync(join(tmpdir(), 'videoscript-media-'));
  const mediaPath = join(directory, 'campione.mp4');
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=black:s=640x360:r=25:d=4', '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=stereo', '-t', '4', '-c:v', 'libx264', '-threads', '2', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-timecode', '01:00:00:00', mediaPath]);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('/');
    await expect(page.getByText('Backend locale connesso')).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('studio-vuoto.png'), fullPage: true });
    await page.getByRole('button', { name: 'Nuovo progetto', exact: true }).click();
    await page.getByLabel('Nome del progetto').fill('Verifica MVP browser');
    await page.getByRole('button', { name: 'Crea progetto', exact: true }).click();
    await expect(page.locator('.project-breadcrumb').getByText('Verifica MVP browser', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Importa video', exact: true }).click();
    await page.getByLabel('Percorso assoluto del video').fill(mediaPath);
    await page.getByRole('dialog').getByRole('button', { name: 'Importa video', exact: true }).click();
    const video = page.locator('video');
    await expect(video).toBeVisible();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2);
    await page.getByRole('button', { name: 'Riproduci', exact: true }).click();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeGreaterThan(0.1);
    await page.getByRole('button', { name: 'Pausa', exact: true }).click();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true);
    await page.getByLabel('Timecode di destinazione').fill('01:00:01:00');
    await page.getByRole('button', { name: 'Vai al TC' }).click();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeCloseTo(1, 1);
    await page.getByRole('button', { name: 'Avanti 1 secondo', exact: true }).click();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeCloseTo(2, 1);
    await page.getByRole('button', { name: 'Indietro 1 secondo', exact: true }).click();
    await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeCloseTo(1, 1);
    await page.getByLabel('Descrizione dell’annotazione').fill('Nota reale creata nel browser');
    await page.getByLabel('Frame IN annotazione').fill('25');
    await page.getByRole('button', { name: '＋ Aggiungi nota' }).click();
    await expect(page.locator('.annotation-card').getByText('Nota reale creata nel browser', { exact: true })).toBeVisible();
    await expect(page.locator('.annotation-card').getByText('01:00:01:00', { exact: true })).toBeVisible();
    await page.locator('.annotation-card').getByRole('button', { name: 'Modifica' }).click();
    await page.getByLabel('Descrizione dell’annotazione').fill('Nota corretta e persistente');
    await page.getByRole('button', { name: 'Salva modifica' }).click();
    await expect(page.locator('.annotation-card').getByText('Nota corretta e persistente', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.locator('.annotation-card').getByText('Nota corretta e persistente', { exact: true })).toBeVisible();
    await page.getByRole('tab', { name: /^QC/ }).click();
    await page.getByRole('button', { name: 'Avvia analisi QC' }).click();
    await expect(page.locator('.qc-card').first()).toBeVisible({ timeout: 20_000 });
    const black = page.locator('.qc-card').filter({ hasText: 'Black detect' });
    await expect(black.getByText('WARNING', { exact: true })).toBeVisible();
    await black.getByRole('button', { name: 'Conferma', exact: true }).click();
    await expect(black.getByText('Confermato', { exact: true })).toBeVisible();
    await black.locator('.tc-link').click();
    await expect.poll(() => page.locator('video').evaluate((v: HTMLVideoElement) => v.currentTime)).toBeLessThan(0.1);
    await page.screenshot({ path: testInfo.outputPath('studio-qc.png'), fullPage: true });
    await page.getByRole('button', { name: 'Esporta', exact: true }).click();
    const jsonLink = page.getByRole('link').filter({ hasText: 'JSON completo' });
    const href = await jsonLink.getAttribute('href');
    const exported = await request.get(href!);
    expect(exported.ok()).toBeTruthy();
    expect((await exported.json()).annotations[0].description).toBe('Nota corretta e persistente');
    expect(errors).toEqual([]);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});
